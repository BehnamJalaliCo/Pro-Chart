def _slugify(text: str) -> str:
    t = re.sub(r"[^\w\s-]", "", (text or "").strip().lower(), flags=re.UNICODE)
    t = re.sub(r"[\s_]+", "-", t).strip("-")
    t = re.sub(r"-{2,}", "-", t)
    return t[:70].strip("-") or "post"


