def classify_tags(title: str, text: str, category: str | None) -> list[str]:
    """برچسبِ موضوعیِ یک مقاله را از روی متن و دسته استخراج می‌کند (برای backfillِ مقالاتِ قدیمی)."""
    hay = f"{title or ''} {text or ''}".lower()
    tags: list[str] = list(_CAT_TAG.get(category or "", []))
    for triggers, tg in _TRIGGERS:
        if any(t in hay for t in triggers):
            for x in tg:
                if x not in tags:
                    tags.append(x)
    return tags[:5]


def pick_targets() -> list[dict]:
    """همهٔ هدف‌های محتوا: ابتدا صفحاتِ مادر (pillar)، سپس اقماری‌ها.
    هر هدف: {title, tags, pillar_slug, is_pillar, prefix}."""
    pillars, children = [], []
    for key, (pillar_title, tags, kids) in CLUSTERS.items():
        pillar_slug = f"blog-{_slugify(pillar_title)}"
        pillars.append({
            "title": pillar_title, "tags": tags, "pillar_slug": pillar_slug,
            "is_pillar": True, "prefix": pillar_slug,
        })
        for kid in kids:
            children.append({
                "title": kid, "tags": tags, "pillar_slug": pillar_slug,
                "is_pillar": False, "prefix": f"blog-{_slugify(kid)}",
            })
    return pillars + children
