export function tr(lang, key) {
  return (dict[lang] && dict[lang][key]) || dict.fa[key] || key;
}

// هوکِ ترجمه — با تغییرِ زبان، کامپوننت‌ها دوباره رندر می‌شوند.
export function useT() {
  const lang = useApp((s) => s.lang);
  return (key) => tr(lang, key);
}
